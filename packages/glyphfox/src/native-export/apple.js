// iOS asset catalog (one SVG image set per icon, vector data preserved and
// template rendering, so the tint color applies) and the SwiftUI helpers
// that name every image: Image(glyphfox: .home).

import { SITE, assertUnique, camelCase, noColor, pascalCase, svgColor, svgDocument } from './shared.js';

export const RENDERING = ['template', 'original'];

const SWIFT_KEYWORDS = new Set(
  'associatedtype borrowing class consuming deinit enum extension fileprivate func import init inout internal let nonisolated open operator package precedencegroup private protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self Self super throws true try'.split(' '),
);
// Members of the generated enum (and words the compiler treats specially even in backticks).
const SWIFT_TAKEN = new Set(['allCases', 'rawValue', 'hashValue', 'init', 'self', 'Self', 'Type', 'Protocol']);

/** Swift enum case for an icon: arrow-right becomes arrowRight, repeat becomes `repeat`. */
export function swiftCase(base) {
  let name = camelCase(base);
  if (/^\d/.test(name)) name = `icon${pascalCase(base)}`;
  if (SWIFT_TAKEN.has(name)) name += 'Icon';
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

/** Contents.json the way Xcode writes it (sorted keys, two spaces, " : "). */
export function xcodeJson(value) {
  const sort = (v) => {
    if (Array.isArray(v)) return v.map(sort);
    if (v && typeof v === 'object') return Object.fromEntries(Object.keys(v).sort().map((k) => [k, sort(v[k])]));
    return v;
  };
  return JSON.stringify(sort(value), null, 2).replace(/^(\s*"(?:[^"\\]|\\.)*"): /gm, '$1 : ') + '\n';
}

const INFO = { author: 'xcode', version: 1 };

function catalogOptions(options) {
  const prefix = options.prefix === undefined || options.prefix === null || options.prefix === true ? 'gf-' : String(options.prefix);
  if (!/^[A-Za-z0-9_.-]*$/.test(prefix)) throw new Error(`"${prefix}" cannot start an asset name; use letters, digits, dots, dashes or underscores`);
  // Template by default so the tint applies; a baked --color stays visible with original rendering.
  const rendering = options.rendering === undefined || options.rendering === null || options.rendering === true ? (noColor(options.color) ? 'template' : 'original') : String(options.rendering);
  if (!RENDERING.includes(rendering)) throw new RangeError(`unknown rendering "${rendering}" (use ${RENDERING.join(' or ')})`);
  const catalog = String(options.catalog || 'GlyphFox.xcassets').replace(/\\/g, '/').replace(/\/+$/, '');
  if (!catalog.endsWith('.xcassets')) throw new Error(`the asset catalog must end with .xcassets, got "${catalog}"`);
  return { prefix, rendering, catalog };
}

/** Files for `glyphfox export ios`: CATALOG/Contents.json and CATALOG/gf-NAME.imageset/{Contents.json, gf-NAME.svg}. */
export function iosFiles(items, options = {}) {
  const { prefix, rendering, catalog } = catalogOptions(options);
  svgColor(options.color, 'ios');
  svgColor(options.secondaryColor, 'ios');
  for (const it of items) it.asset = `${prefix}${it.base}`;
  assertUnique(items, (it) => it.asset, 'image set');
  const files = { [`${catalog}/Contents.json`]: xcodeJson({ info: INFO }) };
  for (const it of items) {
    const image = { filename: `${it.asset}.svg`, idiom: 'universal' };
    if (it.geometry.mirror) image['language-direction'] = 'left-to-right';
    files[`${catalog}/${it.asset}.imageset/Contents.json`] = xcodeJson({
      images: [image],
      info: INFO,
      properties: { 'preserves-vector-representation': true, 'template-rendering-intent': rendering },
    });
    files[`${catalog}/${it.asset}.imageset/${it.asset}.svg`] = svgDocument(it.geometry, { ...options, platform: 'ios' });
  }
  return files;
}

/** GlyphFox.swift: the GlyphFox enum, Image(glyphfox:) and UIImage.glyphfox(_:). */
export function swiftFile(items, options = {}) {
  const { rendering, catalog } = catalogOptions(options);
  const first = items[0] ? swiftCase(items[0].base).replace(/`/g, '') : 'home';
  const mode = rendering === 'template' ? ['.template', '.alwaysTemplate'] : ['.original', '.alwaysOriginal'];
  const book = catalog.split('/').pop();
  return [
    `// glyphfox icons for SwiftUI and UIKit (MIT license, ${SITE}).`,
    `// Generated by glyphfox export swiftui. The images live in ${book}.`,
    '',
    'import SwiftUI',
    '#if canImport(UIKit)',
    'import UIKit',
    '#endif',
    '',
    `/// The glyphfox icons of ${book}: Image(glyphfox: .${first}).`,
    'public enum GlyphFox: String, CaseIterable, Sendable {',
    ...items.map((it) => `    case ${it.swift} = "${it.asset}"`),
    '}',
    '',
    'public extension Image {',
    `    /// A glyphfox icon from the asset catalog, rendered as ${rendering === 'template' ? 'a template so it takes the foreground style' : 'drawn, with its own colors'}.`,
    '    init(glyphfox icon: GlyphFox, bundle: Bundle? = nil) {',
    `        self = Image(icon.rawValue, bundle: bundle).renderingMode(${mode[0]})`,
    '    }',
    '}',
    '',
    '#if canImport(UIKit)',
    'public extension UIImage {',
    '    /// A glyphfox icon from the asset catalog for UIKit.',
    '    static func glyphfox(_ icon: GlyphFox, in bundle: Bundle? = nil) -> UIImage? {',
    `        UIImage(named: icon.rawValue, in: bundle, with: nil)?.withRenderingMode(${mode[1]})`,
    '    }',
    '}',
    '#endif',
    '',
  ].join('\n');
}

/** Files for `glyphfox export swiftui`: GlyphFox.swift next to the asset catalog it reads. */
export function swiftuiFiles(items, options = {}) {
  const files = iosFiles(items, options);
  for (const it of items) it.swift = swiftCase(it.base);
  assertUnique(items, (it) => it.swift.replace(/`/g, ''), 'Swift case');
  files['GlyphFox.swift'] = swiftFile(items, options);
  return files;
}

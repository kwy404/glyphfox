// Jetpack Compose ImageVector files: GlyphFox.kt declares the GlyphFox
// object, and each icon is a lazily built extension property on it, so
// `Icon(GlyphFox.Home, contentDescription = null)` works and R8 drops the
// icons an app never uses.

import { SITE, assertUnique, hex2, noColor, num, parseHex, pascalCase, walkPath } from './shared.js';

const IMPORTS = {
  color: 'androidx.compose.ui.graphics.Color',
  fillType: 'androidx.compose.ui.graphics.PathFillType',
  solid: 'androidx.compose.ui.graphics.SolidColor',
  cap: 'androidx.compose.ui.graphics.StrokeCap',
  join: 'androidx.compose.ui.graphics.StrokeJoin',
  vector: 'androidx.compose.ui.graphics.vector.ImageVector',
  group: 'androidx.compose.ui.graphics.vector.group',
  path: 'androidx.compose.ui.graphics.vector.path',
  dp: 'androidx.compose.ui.unit.dp',
};

// Names the generated files use; an icon with one of them gets an Icon suffix.
const KOTLIN_TAKEN = new Set(['Color', 'SolidColor', 'StrokeCap', 'StrokeJoin', 'PathFillType', 'ImageVector', 'GlyphFox']);

/** Kotlin property name for an icon: arrow-right becomes ArrowRight. */
export function kotlinName(base) {
  const p = pascalCase(base);
  if (/^\d/.test(p)) return `Icon${p}`;
  return KOTLIN_TAKEN.has(p) ? `${p}Icon` : p;
}

/** A Kotlin Color expression for a hex color, Color.Black by default. */
export function kotlinColor(value, fallback = 'Color.Black') {
  if (noColor(value)) return fallback;
  const c = parseHex(value);
  if (!c) throw new RangeError(`compose takes a hex color such as #ff7a1a, got "${value}"`);
  return `Color(0x${hex2(c.a * 255)}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)})`;
}

const f = (v) => `${num(v)}f`;

/** PathBuilder calls for absolute segments. */
export function pathCalls(segs) {
  const out = [];
  walkPath(segs, (cmd, n) => {
    if (cmd === 'M') out.push(`moveTo(${f(n[0])}, ${f(n[1])})`);
    else if (cmd === 'L') out.push(`lineTo(${f(n[0])}, ${f(n[1])})`);
    else if (cmd === 'H') out.push(`horizontalLineTo(${f(n[0])})`);
    else if (cmd === 'V') out.push(`verticalLineTo(${f(n[0])})`);
    else if (cmd === 'C') out.push(`curveTo(${n.map(f).join(', ')})`);
    else if (cmd === 'Q') out.push(`quadTo(${n.map(f).join(', ')})`);
    else if (cmd === 'A') out.push(`arcTo(${f(n[0])}, ${f(n[1])}, ${f(n[2])}, ${n[3] ? 'true' : 'false'}, ${n[4] ? 'true' : 'false'}, ${f(n[5])}, ${f(n[6])})`);
    else if (cmd === 'Z') out.push('close()');
  });
  return out;
}

/** The Kotlin source of one icon. */
export function imageVectorFile(item, options = {}) {
  const g = item.geometry;
  const name = item.kotlin;
  const cache = `_${name[0].toLowerCase()}${name.slice(1)}`;
  const pkg = options.package || 'glyphfox';
  const used = new Set(['vector', 'dp', 'path', 'solid', 'color']);
  const grouped = Boolean(g.rotate || g.flipX || g.flipY);
  const stroke = kotlinColor(options.color);
  const fill = noColor(options.secondaryColor) ? stroke : kotlinColor(options.secondaryColor);
  const pad = grouped ? ' '.repeat(16) : ' '.repeat(12);
  const blocks = [];
  const block = (args, segs) => {
    const lines = [`${pad}path(`, ...args.map((a) => `${pad}    ${a},`), `${pad}) {`, ...pathCalls(segs).map((c) => `${pad}    ${c}`), `${pad}}`];
    blocks.push(lines.join('\n'));
  };
  for (const fl of g.fills) {
    const args = [`fill = SolidColor(${fill})`];
    if (fl.opacity < 1) args.push(`fillAlpha = ${f(fl.opacity)}`);
    if (fl.evenOdd) {
      args.push('pathFillType = PathFillType.EvenOdd');
      used.add('fillType');
    }
    block(args, fl.segs);
  }
  if (g.strokes.length) {
    used.add('cap');
    used.add('join');
  }
  const cap = g.cap === 'square' ? 'StrokeCap.Square' : 'StrokeCap.Round';
  const join = g.join === 'miter' ? 'StrokeJoin.Miter' : 'StrokeJoin.Round';
  for (const segs of g.strokes) block([`stroke = SolidColor(${stroke})`, `strokeLineWidth = ${f(g.strokeWidth)}`, `strokeLineCap = ${cap}`, `strokeLineJoin = ${join}`], segs);
  let content = blocks.join('\n');
  if (grouped) {
    used.add('group');
    const args = [g.rotate ? `rotate = ${f(g.rotate)}` : null, 'pivotX = 12f', 'pivotY = 12f', g.flipX ? 'scaleX = -1f' : null, g.flipY ? 'scaleY = -1f' : null].filter(Boolean);
    content = [`            group(`, ...args.map((a) => `                ${a},`), '            ) {', content, '            }'].join('\n');
  }
  const builder = [
    `name = "GlyphFox.${name}"`,
    `defaultWidth = ${num(g.size)}.dp`,
    `defaultHeight = ${num(g.size)}.dp`,
    'viewportWidth = 24f',
    'viewportHeight = 24f',
    g.mirror ? 'autoMirror = true' : null,
  ].filter(Boolean);
  const imports = Object.keys(IMPORTS)
    .filter((k) => used.has(k))
    .map((k) => IMPORTS[k])
    .sort();
  return [
    `// glyphfox icon "${item.spec}" (MIT license, ${SITE}).`,
    '// Generated by glyphfox export compose.',
    `package ${pkg}`,
    '',
    ...imports.map((i) => `import ${i}`),
    '',
    `/** The glyphfox icon "${item.spec}". */`,
    `val GlyphFox.${name}: ImageVector`,
    '    get() {',
    `        if (${cache} != null) {`,
    `            return ${cache}!!`,
    '        }',
    `        ${cache} = ImageVector.Builder(`,
    ...builder.map((b) => `            ${b},`),
    '        ).apply {',
    content,
    '        }.build()',
    `        return ${cache}!!`,
    '    }',
    '',
    `private var ${cache}: ImageVector? = null`,
    '',
  ].join('\n');
}

/** GlyphFox.kt: the object that holds the icons and a map of every exported icon. */
export function glyphFoxObject(items, options = {}) {
  const pkg = options.package || 'glyphfox';
  const first = items[0] ? items[0].kotlin : 'Home';
  return [
    `// glyphfox icons for Jetpack Compose (MIT license, ${SITE}).`,
    '// Generated by glyphfox export compose. Each icon lives in its own file.',
    `package ${pkg}`,
    '',
    `import ${IMPORTS.vector}`,
    '',
    `/** glyphfox icons as ImageVector: Icon(GlyphFox.${first}, contentDescription = null). */`,
    'object GlyphFox {',
    '    /** Every icon of this export, by its glyphfox name. */',
    '    val all: Map<String, ImageVector> by lazy {',
    '        mapOf(',
    ...items.map((it) => `            "${it.spec.replace(/["\\$]/g, '\\$&')}" to ${it.kotlin},`),
    '        )',
    '    }',
    '}',
    '',
  ].join('\n');
}

/** Files for `glyphfox export compose`: PACKAGE/GlyphFox.kt and PACKAGE/NAME.kt. */
export function composeFiles(items, options = {}) {
  const pkg = options.package === undefined || options.package === null || options.package === true ? 'glyphfox' : String(options.package);
  if (!/^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/.test(pkg)) throw new Error(`"${pkg}" is not a valid Kotlin package name`);
  for (const it of items) it.kotlin = kotlinName(it.base);
  assertUnique([{ spec: '(the GlyphFox object)', kotlin: 'GlyphFox' }, ...items], (it) => it.kotlin, 'Kotlin file');
  kotlinColor(options.color);
  if (!noColor(options.secondaryColor)) kotlinColor(options.secondaryColor);
  const dir = pkg.split('.').join('/');
  const opts = { ...options, package: pkg };
  const files = { [`${dir}/GlyphFox.kt`]: glyphFoxObject(items, opts) };
  for (const it of items) files[`${dir}/${it.kotlin}.kt`] = imageVectorFile(it, opts);
  return files;
}

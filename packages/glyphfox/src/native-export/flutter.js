// Flutter: SVG assets, a Dart file with one constant per icon and a tiny
// GlyphFoxIcon widget (flutter_svg) that follows IconTheme like Icon does.

import { SITE, assertUnique, camelCase, noColor, pascalCase, svgColor, svgDocument } from './shared.js';

const DART_RESERVED = new Set(
  'assert break case catch class const continue default do else enum extends false final finally for if in is new null rethrow return super switch this throw true try var void while with'.split(' '),
);

/** Dart constant for an icon: arrow-right becomes arrowRight. */
export function dartName(base) {
  let name = camelCase(base);
  if (/^\d/.test(name)) name = `icon${pascalCase(base)}`;
  return DART_RESERVED.has(name) || name === 'values' ? `${name}Icon` : name;
}

const dartString = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

/** lib/glyphfox.dart: the GlyphFoxIcons constants and the GlyphFoxIcon widget. */
export function dartFile(items, { assets, baked = false }) {
  const first = items[0] ? items[0].dart : 'home';
  return [
    `// glyphfox icons for Flutter (MIT license, ${SITE}).`,
    '// Generated by glyphfox export flutter. Needs flutter_svg and the assets in pubspec.yaml:',
    '//',
    '//   dependencies:',
    '//     flutter_svg: ^2.0.0',
    '//   flutter:',
    '//     assets:',
    `//       - ${assets}/`,
    '',
    "import 'package:flutter/widgets.dart';",
    "import 'package:flutter_svg/flutter_svg.dart';",
    '',
    '/// Asset paths of the glyphfox icons in this export.',
    'class GlyphFoxIcons {',
    '  GlyphFoxIcons._();',
    '',
    ...items.flatMap((it) => [`  /// The glyphfox icon ${it.spec}.`, `  static const String ${it.dart} = ${dartString(`${assets}/${it.base}.svg`)};`]),
    '',
    '  /// Every icon of this export.',
    `  static const List<String> values = <String>[${items.map((it) => it.dart).join(', ')}];`,
    '}',
    '',
    `/// A glyphfox icon that follows the surrounding IconTheme: GlyphFoxIcon(GlyphFoxIcons.${first}).`,
    'class GlyphFoxIcon extends StatelessWidget {',
    '  /// Draws [icon], one of the [GlyphFoxIcons] paths.',
    '  const GlyphFoxIcon(this.icon, {super.key, this.size, this.color, this.semanticLabel, this.matchTextDirection = false});',
    '',
    '  /// One of the GlyphFoxIcons paths.',
    '  final String icon;',
    '',
    '  /// Width and height, IconTheme size by default.',
    '  final double? size;',
    '',
    baked ? '  /// Tint of the whole icon; without it the exported colors stay. The duotone layer keeps its opacity.' : '  /// Tint of the whole icon, IconTheme color by default. The duotone layer keeps its opacity.',
    '  final Color? color;',
    '',
    '  /// Accessible name; without it the icon is decorative.',
    '  final String? semanticLabel;',
    '',
    '  /// Mirrors the icon in right to left layouts.',
    '  final bool matchTextDirection;',
    '',
    '  @override',
    '  Widget build(BuildContext context) {',
    '    final IconThemeData theme = IconTheme.of(context);',
    '    final double side = size ?? theme.size ?? 24;',
    baked ? '    final Color? tint = color;' : '    final Color? tint = color ?? theme.color;',
    '    return SvgPicture.asset(',
    '      icon,',
    '      width: side,',
    '      height: side,',
    '      colorFilter: tint == null ? null : ColorFilter.mode(tint, BlendMode.srcIn),',
    '      matchTextDirection: matchTextDirection,',
    '      semanticsLabel: semanticLabel,',
    '      excludeFromSemantics: semanticLabel == null,',
    '    );',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Files for `glyphfox export flutter`: assets/glyphfox/NAME.svg and lib/glyphfox.dart. */
export function flutterFiles(items, options = {}, notes = []) {
  const assets = String(options.assets && options.assets !== true ? options.assets : 'assets/glyphfox')
    .replace(/\\/g, '/')
    .replace(/^\.\/|\/+$/g, '');
  svgColor(options.color, 'flutter');
  svgColor(options.secondaryColor, 'flutter');
  for (const it of items) it.dart = dartName(it.base);
  assertUnique(items, (it) => it.dart, 'Dart constant');
  const files = {};
  for (const it of items) files[`${assets}/${it.base}.svg`] = svgDocument(it.geometry, { ...options, platform: 'flutter' });
  files['lib/glyphfox.dart'] = dartFile(items, { assets, baked: !noColor(options.color) });
  notes.push(`flutter: add flutter_svg to the dependencies and ${assets}/ to the flutter assets in pubspec.yaml`);
  return files;
}
